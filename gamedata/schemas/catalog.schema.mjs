export function validateEnumsRecord(enums, path = "enums") {
  const errors = [];
  if (!checkFields(
    enums,
    {
      baseTypes: isArray,
      attackTypes: isArray,
      skillTypes: isArray,
      skillItemTypes: isArray,
      equipSlots: isArray,
      categories: isArray,
      usedTogetherCategories: isArray,
    },
    path,
    errors,
  )) {
    return { ok: false, errors };
  }
  for (const key of ["baseTypes", "attackTypes", "skillTypes", "skillItemTypes", "equipSlots", "categories", "usedTogetherCategories"]) {
    const list = enums[key];
    if (!isArray(list)) continue;
    for (const [index, entry] of list.entries()) {
      checkFields(entry, { id: isNullable(isEnumId), name: isString }, `${path}.${key}[${index}]`, errors);
    }
  }
  return { ok: errors.length === 0, errors };
}

export function validateManifest(manifest, path = "manifest") {
  const errors = [];
  if (!checkFields(
    manifest,
    {
      contentVersion: isString,
      generatedAt: isString,
      rulesetVersion: isString,
      schemaVersion: isString,
      counts: isPlainObject,
      parserVersions: isPlainObject,
      warnings: isArray,
      itemIndexNote: isString,
    },
    path,
    errors,
  )) {
    return { ok: false, errors };
  }
  checkExtraKeys(
    manifest,
    ["contentVersion", "generatedAt", "rulesetVersion", "schemaVersion", "counts", "parserVersions", "warnings", "itemIndexNote"],
    path,
    errors,
  );
  if (!/^[0-9a-f]{64}$/.test(manifest.contentVersion || "")) {
    errors.push(`${path}.contentVersion: expected a 64-char sha256 hex digest`);
  }
  for (const [key, value] of Object.entries(manifest.counts || {})) {
    if (!isFiniteNumber(value)) errors.push(`${path}.counts.${key}: expected number`);
  }
  for (const [key, value] of Object.entries(manifest.parserVersions || {})) {
    if (!isString(value)) errors.push(`${path}.parserVersions.${key}: expected string`);
  }
  validateWarnings(manifest.warnings, `${path}.warnings`, errors);
  return { ok: errors.length === 0, errors };
}

export function validateQualityReport(report, path = "qualityReport") {
  const errors = [];
  if (!checkFields(report, { generatedAt: isString, checks: isArray }, path, errors)) {
    return { ok: false, errors };
  }
  checkExtraKeys(report, ["generatedAt", "checks"], path, errors);
  if (isArray(report.checks)) {
    for (const [index, check] of report.checks.entries()) {
      const checkPath = `${path}.checks[${index}]`;
      checkFields(
        check,
        { check: isString, severity: oneOf(["error", "warning", "info"]), count: isFiniteNumber, samples: isArray },
        checkPath,
        errors,
      );
      checkExtraKeys(check, ["check", "severity", "count", "samples", "note"], checkPath, errors);
    }
  }
  return { ok: errors.length === 0, errors };
}

/**
 * Validates the whole generated catalog and the cross-file referential
 * integrity rules from design doc 22.
 */
export function validateCatalog(catalog) {
  const errors = [];
  const counts = {};
  const check = (result, label) => {
    if (!result.ok) errors.push(...result.errors.slice(0, 10).map((e) => `${label}: ${e}`));
    return result.ok;
  };

  check(validateManifest(catalog.manifest), "manifest");
  check(validateEnumsRecord(catalog.enums), "enums");
  check(validateQualityReport(catalog.qualityReport), "quality-report");

  const professionIds = new Set();
  for (const [index, record] of (catalog.professions || []).entries()) {
    check(validateProfessionRecord(record, `professions[${index}]`), "professions");
    professionIds.add(record.id);
  }
  const raceIds = new Set();
  for (const [index, record] of (catalog.races || []).entries()) {
    check(validateRaceRecord(record, `races[${index}]`), "races");
    raceIds.add(record.id);
  }
  counts.professions = professionIds.size;
  counts.races = raceIds.size;

  const skillIds = new Set();
  for (const [index, record] of (catalog.skills || []).entries()) {
    check(validateSkillRecord(record, `skills[${index}]`), "skills");
    if (skillIds.has(record.id)) errors.push(`skills[${index}].id: duplicate ${record.id}`);
    skillIds.add(record.id);
  }
  counts.skills = skillIds.size;

  const itemIds = new Set();
  for (const [index, record] of (catalog.items || []).entries()) {
    check(validateItemRecord(record, `items[${index}]`), "items");
    if (itemIds.has(record.id)) errors.push(`items[${index}].id: duplicate ${record.id}`);
    itemIds.add(record.id);
  }
  counts.items = itemIds.size;

  let relations = 0;
  for (const [index, record] of (catalog.skillRelations || []).entries()) {
    check(validateLearnableSkill(record, `skillRelations[${index}]`), "skill-relations");
    relations += 1;
    if (!skillIds.has(record.skillId)) {
      errors.push(`skillRelations[${index}].skillId: unknown skill ${record.skillId}`);
    }
    const ownerOk = record.ownerKind === "profession" ? professionIds.has(record.ownerId) : raceIds.has(record.ownerId);
    if (!ownerOk) errors.push(`skillRelations[${index}].ownerId: unknown ${record.ownerKind} ${record.ownerId}`);
  }
  counts.skillRelations = relations;

  return { ok: errors.length === 0, errors, counts };
}
